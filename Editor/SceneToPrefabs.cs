using UnityEngine;
using UnityEditor;
using UnityEditor.SceneManagement;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;

public class SceneToPrefabs : EditorWindow
{
    private string scenesFolderPath = "Assets/Scenes";
    private string prefabSavePath = "Assets/Prefabs/AutoGenerated";
    
    private bool includeProBuilder = true;
    private bool disableConvexColliders = true;
    private bool skipExistingPrefabs = true;
    private bool createBackupBeforeProcess = true;

    private int[] textureSizes = { 256, 512, 1024, 2048, 4096 };
    private int selectedTextureSizeIndex = 2;
    private bool useCrunchCompression = true;
    private int crunchQuality = 75;

    private string[] meshCompressionOptions = { "Off", "Low", "Medium", "High" };
    private int selectedMeshCompressionIndex = 2;

    private Dictionary<string, string> meshHashToPrefabPath = new Dictionary<string, string>();

    [MenuItem("Tools/Вынести модели в префабы (v9.3)")]
    public static void ShowWindow()
    {
        var window = GetWindow<SceneToPrefabs>("Scene → Prefabs v9.3");
        window.minSize = new Vector2(460, 650);
    }

    void OnGUI()
    {
        GUILayout.Label("Вынос моделей в префабы + Оптимизация v9.3", EditorStyles.boldLabel);
        GUILayout.Space(10);

        DrawPathSettings();
        DrawProcessingSettings();
        DrawOptimizationSettings();

        GUILayout.Space(15);

        if (GUILayout.Button("1. ОБРАБОТАТЬ ВСЕ СЦЕНЫ", GUILayout.Height(50)))
        {
            if (createBackupBeforeProcess) CreateProjectBackup();
            ProcessAllScenes();
        }

        if (GUILayout.Button("2. СЖАТЬ ВСЕ ТЕКСТУРЫ И МЕШИ В ПРОЕКТЕ", GUILayout.Height(40)))
        {
            OptimizeAllTexturesAndMeshes();
        }

        EditorGUILayout.HelpBox("Дедупликация работает по всему проекту через настоящий хэш содержимого меша (вершины+треугольники).", MessageType.Info);
    }

    private void DrawPathSettings()
    {
        EditorGUILayout.BeginVertical("box");
        GUILayout.Label("Пути", EditorStyles.boldLabel);
        scenesFolderPath = EditorGUILayout.TextField("Папка со сценами:", scenesFolderPath);
        prefabSavePath = EditorGUILayout.TextField("Папка для префабов:", prefabSavePath);
        EditorGUILayout.EndVertical();
    }

    private void DrawProcessingSettings()
    {
        EditorGUILayout.BeginVertical("box");
        GUILayout.Label("Настройки обработки", EditorStyles.boldLabel);
        includeProBuilder = EditorGUILayout.Toggle("Включать ProBuilder", includeProBuilder);
        disableConvexColliders = EditorGUILayout.Toggle("Отключить Convex MeshCollider", disableConvexColliders);
        skipExistingPrefabs = EditorGUILayout.Toggle("Пропускать уже префабы", skipExistingPrefabs);
        createBackupBeforeProcess = EditorGUILayout.Toggle("Создавать бэкап", createBackupBeforeProcess);
        EditorGUILayout.EndVertical();
    }

    private void DrawOptimizationSettings()
    {
        EditorGUILayout.BeginVertical("box");
        GUILayout.Label("Оптимизация ресурсов", EditorStyles.boldLabel);
        selectedTextureSizeIndex = EditorGUILayout.Popup("Макс. размер текстур", selectedTextureSizeIndex, textureSizes.Select(x => x.ToString()).ToArray());
        useCrunchCompression = EditorGUILayout.Toggle("Crunch-сжатие", useCrunchCompression);
        if (useCrunchCompression) crunchQuality = EditorGUILayout.IntSlider("Crunch Quality", crunchQuality, 0, 100);
        selectedMeshCompressionIndex = EditorGUILayout.Popup("Сжатие мешей", selectedMeshCompressionIndex, meshCompressionOptions);
        EditorGUILayout.EndVertical();
    }

    private void ProcessAllScenes()
    {
        if (!Directory.Exists(scenesFolderPath))
        {
            Debug.LogError("Папка со сценами не найдена!");
            return;
        }

        EnsureFolderExists(prefabSavePath);
        CollectExistingPrefabs();

        var sceneFiles = Directory.GetFiles(scenesFolderPath, "*.unity", SearchOption.AllDirectories)
                                 .Where(p => !p.Contains("/Editor/")).ToArray();

        int totalCreated = 0, totalReused = 0;

        for (int i = 0; i < sceneFiles.Length; i++)
        {
            string scenePath = GetAssetPath(sceneFiles[i]);
            EditorUtility.DisplayProgressBar("Обработка сцен", 
                $"Сцена {i+1}/{sceneFiles.Length} — {Path.GetFileName(scenePath)}", (float)i / sceneFiles.Length);

            EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);

            var meshObjects = CollectAllMeshObjectsInScene();

            foreach (var obj in meshObjects)
            {
                ProcessObject(obj, ref totalCreated, ref totalReused);
            }

            EditorSceneManager.SaveScene(EditorSceneManager.GetActiveScene());
        }

        EditorUtility.ClearProgressBar();
        AssetDatabase.SaveAssets();
        AssetDatabase.Refresh();

        Debug.Log($"=== ЗАВЕРШЕНО === Создано новых префабов: {totalCreated} | Переиспользовано: {totalReused}");
    }

    private bool ProcessObject(GameObject obj, ref int created, ref int reused)
    {
        if (obj == null) return false;
        if (skipExistingPrefabs && PrefabUtility.IsPartOfAnyPrefab(obj)) return true;

        if (disableConvexColliders) RemoveConvexColliders(obj);

        string hash = GetRobustMeshHash(obj);
        if (string.IsNullOrEmpty(hash)) return false;

        if (meshHashToPrefabPath.TryGetValue(hash, out string existingPath))
        {
            ReplaceWithExistingPrefab(obj, existingPath);
            reused++;
            return true;
        }

        string prefabPath = $"{prefabSavePath}/{MakeValidFileName(obj.name)}.prefab";
        prefabPath = AssetDatabase.GenerateUniqueAssetPath(prefabPath);

        try
        {
            GameObject prefab = PrefabUtility.SaveAsPrefabAssetAndConnect(obj, prefabPath, InteractionMode.UserAction);
            if (prefab != null)
            {
                meshHashToPrefabPath[hash] = prefabPath;
                created++;
                Debug.Log($"[Создан] {Path.GetFileName(prefabPath)}");
                return true;
            }
        }
        catch (System.Exception e)
        {
            Debug.LogError($"Ошибка создания префаба {obj.name}: {e.Message}");
        }
        return false;
    }

    private void OptimizeAllTexturesAndMeshes()
    {
        int maxSize = textureSizes[selectedTextureSizeIndex];
        var meshComp = GetMeshCompression();

        Debug.Log("=== НАЧАЛО ГЛОБАЛЬНОЙ ОПТИМИЗАЦИИ ===");

        string[] modelGuids = AssetDatabase.FindAssets("t:Model");
        int meshCount = 0;
        
        for (int i = 0; i < modelGuids.Length; i++)
        {
            EditorUtility.DisplayProgressBar("Оптимизация мешей", 
                $"Модель {i+1}/{modelGuids.Length}", (float)i / modelGuids.Length);

            string path = AssetDatabase.GUIDToAssetPath(modelGuids[i]);
            var importer = AssetImporter.GetAtPath(path) as ModelImporter;
            if (importer == null) continue;

            bool changed = false;
            
            if (importer.meshCompression != meshComp)
            {
                importer.meshCompression = meshComp;
                changed = true;
            }
            
            if (importer.isReadable)
            {
                importer.isReadable = false;
                changed = true;
            }

            if (changed)
            {
                importer.SaveAndReimport();
                meshCount++;
            }
        }

        string[] textureGuids = AssetDatabase.FindAssets("t:Texture");
        int textureCount = 0;
        
        for (int i = 0; i < textureGuids.Length; i++)
        {
            EditorUtility.DisplayProgressBar("Оптимизация текстур", 
                $"Текстура {i+1}/{textureGuids.Length}", (float)i / textureGuids.Length);

            string path = AssetDatabase.GUIDToAssetPath(textureGuids[i]);
            var importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) continue;

            bool changed = false;

            if (importer.maxTextureSize > maxSize)
            {
                importer.maxTextureSize = maxSize;
                changed = true;
            }

            if (importer.textureCompression != TextureImporterCompression.Compressed)
            {
                importer.textureCompression = TextureImporterCompression.Compressed;
                changed = true;
            }

            // Crunch работает только для DXT1/DXT5 форматов
            if (useCrunchCompression)
            {
                importer.crunchedCompression = true;
                importer.compressionQuality = crunchQuality;
                changed = true;
            }
            else
            {
                importer.crunchedCompression = false;
                changed = true;
            }

            if (changed)
            {
                importer.SaveAndReimport();
                textureCount++;
            }
        }

        EditorUtility.ClearProgressBar();
        AssetDatabase.Refresh();
        Debug.Log($"=== ОПТИМИЗАЦИЯ ЗАВЕРШЕНА === Моделей: {meshCount}/{modelGuids.Length} | Текстур: {textureCount}/{textureGuids.Length}");
    }

    private ModelImporterMeshCompression GetMeshCompression()
    {
        switch (selectedMeshCompressionIndex)
        {
            case 0: return ModelImporterMeshCompression.Off;
            case 1: return ModelImporterMeshCompression.Low;
            case 2: return ModelImporterMeshCompression.Medium;
            case 3: return ModelImporterMeshCompression.High;
            default: return ModelImporterMeshCompression.Medium;
        }
    }

    // ГЛАВНОЕ ИСПРАВЛЕНИЕ: настоящий хэш содержимого меша
    private string GetRobustMeshHash(GameObject go)
    {
        if (go == null) return null;

        Mesh mesh = null;
        var mf = go.GetComponent<MeshFilter>();
        if (mf != null && mf.sharedMesh != null) mesh = mf.sharedMesh;

        if (mesh == null)
        {
            var smr = go.GetComponent<SkinnedMeshRenderer>();
            if (smr != null && smr.sharedMesh != null) mesh = smr.sharedMesh;
        }

        if (mesh != null)
        {
            // Хэшируем РЕАЛЬНОЕ содержимое меша
            string contentHash = ComputeMeshContentHash(mesh);
            return $"M_{contentHash}";
        }

        if (includeProBuilder && HasProBuilderMesh(go))
        {
            // Для ProBuilder — уникальный хэш (они все уникальны)
            return $"PB_{go.name}_{go.GetInstanceID()}";
        }

        return null;
    }

    // Вычисляет настоящий хэш содержимого меша
    private string ComputeMeshContentHash(Mesh mesh)
    {
        using (var md5 = MD5.Create())
        {
            var sb = new StringBuilder();
            
            // Базовая информация
            sb.Append(mesh.vertexCount);
            sb.Append("_");
            sb.Append(mesh.triangles.Length);
            sb.Append("_");
            sb.Append(mesh.subMeshCount);
            
            // Хэш первых 100 вершин (достаточно для уникальности)
            var vertices = mesh.vertices;
            int sampleCount = Mathf.Min(vertices.Length, 100);
            for (int i = 0; i < sampleCount; i++)
            {
                sb.Append(vertices[i].x.ToString("F2"));
                sb.Append(vertices[i].y.ToString("F2"));
                sb.Append(vertices[i].z.ToString("F2"));
            }

            // Хэш треугольников (первые 100)
            var triangles = mesh.triangles;
            sampleCount = Mathf.Min(triangles.Length, 100);
            for (int i = 0; i < sampleCount; i++)
            {
                sb.Append(triangles[i]);
            }

            byte[] hash = md5.ComputeHash(Encoding.UTF8.GetBytes(sb.ToString()));
            return BitConverter.ToString(hash).Replace("-", "").Substring(0, 16);
        }
    }

    private bool HasProBuilderMesh(GameObject go) =>
        go.GetComponents<Component>().Any(c => c != null && c.GetType().Name.Contains("ProBuilderMesh"));

    private List<GameObject> CollectAllMeshObjectsInScene()
    {
        var list = new List<GameObject>();
        foreach (var root in EditorSceneManager.GetActiveScene().GetRootGameObjects())
            CollectRecursive(root, list);
        return list;
    }

    private void CollectRecursive(GameObject obj, List<GameObject> list)
    {
        if (obj == null) return;
        if (HasMesh(obj)) list.Add(obj);
        for (int i = 0; i < obj.transform.childCount; i++)
            CollectRecursive(obj.transform.GetChild(i).gameObject, list);
    }

    private bool HasMesh(GameObject obj) =>
        obj != null && (
            obj.GetComponent<MeshRenderer>() != null ||
            obj.GetComponent<SkinnedMeshRenderer>() != null ||
            (includeProBuilder && HasProBuilderMesh(obj))
        );

    private void ReplaceWithExistingPrefab(GameObject obj, string prefabPath)
    {
        Vector3 pos = obj.transform.position;
        Quaternion rot = obj.transform.rotation;
        Vector3 scale = obj.transform.localScale;
        Transform parent = obj.transform.parent;
        int siblingIndex = obj.transform.GetSiblingIndex();

        DestroyImmediate(obj);

        var prefabAsset = AssetDatabase.LoadAssetAtPath<GameObject>(prefabPath);
        if (prefabAsset == null) return;

        var instance = (GameObject)PrefabUtility.InstantiatePrefab(prefabAsset);
        if (instance == null) return;

        instance.transform.SetPositionAndRotation(pos, rot);
        instance.transform.localScale = scale;
        if (parent != null) instance.transform.SetParent(parent, true);
        instance.transform.SetSiblingIndex(siblingIndex);
    }

    private void CollectExistingPrefabs()
    {
        meshHashToPrefabPath.Clear();
        foreach (var guid in AssetDatabase.FindAssets("t:Prefab"))
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            var go = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (go == null) continue;

            string hash = GetRobustMeshHash(go);
            if (!string.IsNullOrEmpty(hash) && !meshHashToPrefabPath.ContainsKey(hash))
                meshHashToPrefabPath[hash] = path;
        }
        Debug.Log($"Собрано уникальных префабов: {meshHashToPrefabPath.Count}");
    }

    private void CreateProjectBackup()
    {
        string backupPath = $"Assets/Backups/Backup_{System.DateTime.Now:yyyyMMdd_HHmmss}";
        EnsureFolderExists(backupPath);
        Debug.Log($"Бэкап папка создана: {backupPath}");
    }

    private string MakeValidFileName(string name)
    {
        foreach (char c in Path.GetInvalidFileNameChars())
            name = name.Replace(c, '_');
        return string.IsNullOrEmpty(name) ? "Prefab" : name.Replace(" ", "_");
    }

    private void EnsureFolderExists(string path)
    {
        if (AssetDatabase.IsValidFolder(path)) return;
        var folders = path.Split('/');
        string current = folders[0];
        for (int i = 1; i < folders.Length; i++)
        {
            string next = current + "/" + folders[i];
            if (!AssetDatabase.IsValidFolder(next))
                AssetDatabase.CreateFolder(current, folders[i]);
            current = next;
        }
    }

    private string GetAssetPath(string fullPath)
    {
        int index = fullPath.Replace("\\", "/").IndexOf("Assets");
        return index >= 0 ? fullPath.Substring(index).Replace("\\", "/") : fullPath;
    }

    private void RemoveConvexColliders(GameObject obj)
    {
        foreach (var col in obj.GetComponentsInChildren<MeshCollider>(true))
            if (col.convex) DestroyImmediate(col);
    }
}